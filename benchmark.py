# CUDANT_VQPC — benchmark.py
# Hardware limits. What can this GPU actually do?
# Run: python benchmark.py

import torch
import time
import numpy as np
from cage import Cage
from circuit import run_circuit

print("=== CUDANT_VQPC: BENCHMARK ===\n")

# --------------------------------------------------------
# TEST 1: Max lions in the cage
# --------------------------------------------------------

print("--- TEST 1: Max lions (timing) ---\n")
for n in [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024]:
    torch.cuda.synchronize()
    t0 = time.time()
    cage = Cage(n)
    for i in range(n):
        cage.apply_gate(i, "H")
    for i in range(0, n - 1, 2):
        cage.apply_cnot(i, i + 1)
    torch.cuda.synchronize()
    t1 = time.time()
    ms = (t1 - t0) * 1000
    print(f"  {n:>5} lions, {n//2:>4} rods: {ms:8.2f} ms")

print()

# --------------------------------------------------------
# TEST 2: Max shots (timing)
# --------------------------------------------------------

print("--- TEST 2: Max shots (timing) ---\n")
v = torch.tensor([1.0, 0.0, 0.0], dtype=torch.float32, device="cuda")
for shots in [100, 1000, 10000, 100000, 1000000]:
    torch.cuda.synchronize()
    t0 = time.time()
    from measure import measure_n_shots
    result = measure_n_shots(v, n_shots=shots, seed=42)
    torch.cuda.synchronize()
    t1 = time.time()
    ms = (t1 - t0) * 1000
    print(f"  {shots:>8} shots: {ms:8.2f} ms  →  {shots/ms*1000:.0f} shots/sec")

print()

# --------------------------------------------------------
# TEST 3: Circuit depth (timing)
# --------------------------------------------------------

print("--- TEST 3: Circuit depth (timing) ---\n")
for depth in [1, 10, 50, 100, 500, 1000, 5000]:
    gates = ", ".join([f"Rx(1), Rz(1)"] * (depth // 2))
    torch.cuda.synchronize()
    t0 = time.time()
    result = run_circuit(gates, n_shots=0)
    torch.cuda.synchronize()
    t1 = time.time()
    ms = (t1 - t0) * 1000
    print(f"  {depth:>5} gates: {ms:8.2f} ms  (wobble={result['wobble']:.4f})")

print()

# --------------------------------------------------------
# TEST 4: VRAM usage
# --------------------------------------------------------

print("--- TEST 4: VRAM usage ---\n")
torch.cuda.reset_peak_memory_stats()
base = torch.cuda.memory_allocated() / 1e6

cage = Cage(8)
for i in range(8):
    cage.apply_gate(i, "H")
cage.apply_cnot(0, 1)
cage.apply_cnot(2, 3)

peak = torch.cuda.memory_allocated() / 1e6
print(f"  Base: {base:.1f} MB")
print(f"  After 8-lion cage: {peak:.1f} MB")
print(f"  Delta: {peak - base:.1f} MB")
print(f"  GPU total: {torch.cuda.get_device_properties(0).total_memory / 1e6:.0f} MB")
print(f"  Headroom: {torch.cuda.get_device_properties(0).total_memory/1e6 - peak:.0f} MB")

print()

# --------------------------------------------------------
# TEST 5: The limit (how many lions before it gets slow?)
# --------------------------------------------------------

print("--- TEST 5: Finding the limit ---\n")
print("  (Looking for the point where time doubles per lion)\n")

prev_ms = 0
for n in [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192]:
    torch.cuda.synchronize()
    t0 = time.time()
    cage = Cage(n)
    for i in range(n):
        cage.apply_gate(i, "H")
    torch.cuda.synchronize()
    t1 = time.time()
    ms = (t1 - t0) * 1000

    if prev_ms > 0:
        ratio = ms / prev_ms
        marker = "  ← SLOWING" if ratio > 2 else ""
    else:
        ratio = 1
        marker = ""
    print(f"  {n:>5} lions: {ms:8.2f} ms  (×{ratio:.1f}){marker}")
    prev_ms = ms

print()
print("=== BENCHMARK COMPLETE ===\n")
print("  The GPU is the physics engine.")
print("  The numbers above are your spec sheet.")
print("  Anything within these limits = instant.")
print("  Anything beyond = the GPU is working hard.")   

