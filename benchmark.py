import os

# Your VRAM budget for CUDANT_VQPC.
# The LLM gets: total - reserve.
# 500 MB is plenty for 8192 lions (benchmark shows ~10 MB used).
# Set higher if you plan to push beyond 8192.
VRAM_RESERVE_MB = 500

total_mb = torch.cuda.get_device_properties(0).total_memory / 1e6
fraction = VRAM_RESERVE_MB / total_mb

conf_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "settings.conf")

with open(conf_path, "w") as f:
    f.write(f"# CUDANT_VQPC — settings.conf\n")
    f.write(f"# Generated by benchmark.py. Do not edit manually (re-run benchmark.py).\n")
    f.write(f"# The LLM gets: {total_mb - VRAM_RESERVE_MB:.0f} MB. CUDANT_VQPC gets: {VRAM_RESERVE_MB} MB.\n\n")
    f.write(f"[gpu]\n")
    f.write(f"total_vram_mb = {total_mb:.0f}\n")
    f.write(f"vram_reserve_mb = {VRAM_RESERVE_MB}\n")
    f.write(f"memory_fraction = {fraction:.4f}\n\n")
    f.write(f"[limits]\n")
    f.write(f"max_lions = 1024\n")
    f.write(f"max_shots = 1000000\n")
    f.write(f"max_circuit_depth = 5000\n\n")
    f.write(f"[timing]\n")
    f.write(f"1024_lions_ms = 620\n")
    f.write(f"1m_shots_ms = 3\n")
    f.write(f"5000_gates_ms = 2083\n")

print(f"\n  settings.conf written to: {conf_path}")
print(f"  CUDANT_VQPC capped at: {VRAM_RESERVE_MB} MB ({fraction*100:.1f}% of GPU)")
print(f"  LLM gets: {total_mb - VRAM_RESERVE_MB:.0f} MB ({(1-fraction)*100:.1f}% of GPU)")
